var TextExtractor = class {
  constructor(app) {
    this.app = app;
  }
  extractText() {
    const mdView = this.getMarkdownView();
    if (!mdView) {
      return null;
    }
    const editor = mdView.editor;
    if (!editor) {
      return null;
    }
    const selection = editor.getSelection();
    if (selection && selection.length > 0) {
      const from = editor.posToOffset(editor.getCursor("from"));
      const to = editor.posToOffset(editor.getCursor("to"));
      return {
        text: selection,
        hasSelection: true,
        selectionRange: { from, to }
      };
    }
    return {
      text: editor.getValue(),
      hasSelection: false
    };
  }
  getMarkdownView() {
    const activeView = this.app.workspace.getActiveViewOfType(import_obsidian3.MarkdownView);
    if (activeView) {
      return activeView;
    }
    const leaves = this.app.workspace.getLeavesOfType("markdown");
    for (const leaf of leaves) {
      const view = leaf.view;
      if (view instanceof import_obsidian3.MarkdownView && view.getMode() === "source") {
        return view;
      }
    }
    for (const leaf of leaves) {
      const view = leaf.view;
      if (view instanceof import_obsidian3.MarkdownView) {
        return view;
      }
    }
    return null;
  }
};

// src/text/cleaner.ts
var TextCleaner = class {
  clean(originalText) {
    let text = originalText;
    const mappings = [];
    let cleanOffset = 0;
    let originalOffset = 0;
    const processedText = this.processText(text, originalOffset, cleanOffset, mappings);
    return {
      text: processedText.text,
      mappings: processedText.mappings
    };
  }
  processText(text, startOriginalOffset, startCleanOffset, mappings) {
    let result = "";
    let cleanOffset = startCleanOffset;
    let originalOffset = startOriginalOffset;
    let i = 0;
    while (i < text.length) {
      const yamlResult = this.tryExtractYamlFrontMatter(text, i);
      if (yamlResult) {
        for (let j = 0; j < yamlResult.length; j++) {
          mappings.push({
            cleanOffset: -1,
            originalOffset: originalOffset + j
          });
        }
        originalOffset += yamlResult.length;
        i += yamlResult.length;
        continue;
      }
      const codeBlockResult = this.tryExtractCodeBlock(text, i);
      if (codeBlockResult) {
        for (let j = 0; j < codeBlockResult.length; j++) {
          mappings.push({
            cleanOffset: -1,
            originalOffset: originalOffset + j
          });
        }
        originalOffset += codeBlockResult.length;
        i += codeBlockResult.length;
        continue;
      }
      const inlineCodeResult = this.tryExtractInlineCode(text, i);
      if (inlineCodeResult) {
        for (let j = 0; j < inlineCodeResult.length; j++) {
          mappings.push({
            cleanOffset: -1,
            originalOffset: originalOffset + j
          });
        }
        originalOffset += inlineCodeResult.length;
        i += inlineCodeResult.length;
        continue;
      }
      const htmlResult = this.tryExtractHtmlTag(text, i);
      if (htmlResult) {
        for (let j = 0; j < htmlResult.length; j++) {
          mappings.push({
            cleanOffset: -1,
            originalOffset: originalOffset + j
          });
        }
        originalOffset += htmlResult.length;
        i += htmlResult.length;
        continue;
      }
      const linkResult = this.tryExtractLink(text, i);
      if (linkResult) {
        const displayText = linkResult.displayText;
        for (let j = 0; j < linkResult.urlPart.length; j++) {
          mappings.push({
            cleanOffset: -1,
            originalOffset: originalOffset + j
          });
        }
        originalOffset += linkResult.urlPart.length;
        i += linkResult.urlPart.length;
        for (let j = 0; j < displayText.length; j++) {
          mappings.push({
            cleanOffset: cleanOffset + j,
            originalOffset: originalOffset + j
          });
        }
        result += displayText;
        cleanOffset += displayText.length;
        originalOffset += displayText.length;
        i += displayText.length;
        continue;
      }
      mappings.push({
        cleanOffset,
        originalOffset
      });
      result += text[i];
      cleanOffset++;
      originalOffset++;
      i++;
    }
    return { text: result, mappings };
  }
  tryExtractYamlFrontMatter(text, start) {
    if (start !== 0)
      return null;
    if (!text.startsWith("---", start))
      return null;
    const endIndex = text.indexOf("---", 3);
    if (endIndex === -1)
      return null;
    return text.substring(start, endIndex + 3);
  }
  tryExtractCodeBlock(text, start) {
    if (!text.startsWith("```", start))
      return null;
    const endIndex = text.indexOf("```", start + 3);
    if (endIndex === -1)
      return null;
    return text.substring(start, endIndex + 3);
  }
  tryExtractInlineCode(text, start) {
    if (text[start] !== "`")
      return null;
    if (text.startsWith("```", start))
      return null;
    const endIndex = text.indexOf("`", start + 1);
    if (endIndex === -1)
      return null;
    return text.substring(start, endIndex + 1);
  }
  tryExtractHtmlTag(text, start) {
    if (text[start] !== "<")
      return null;
    const endIndex = text.indexOf(">", start);
    if (endIndex === -1)
      return null;
    return text.substring(start, endIndex + 1);
  }
  tryExtractLink(text, start) {
    const linkRegex = /^\[([^\]]*)\]\(([^)]+)\)/;
    const match = text.substring(start).match(linkRegex);
    if (!match)
      return null;
    const fullMatch = match[0];
    const displayText = match[1];
    const urlPart = fullMatch.substring(fullMatch.indexOf("]("));
    return {
      urlPart: `](${match[2]})`,
      displayText
    };
  }
};

