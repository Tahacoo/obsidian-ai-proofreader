  applyFilteredFixes() {
    const editor = this.plugin.getEditor();
    if (!editor)
      return;
    const resultKey = (r) => r.paragraphIndex !== void 0 ? r.paragraphIndex * 1e7 + r.offsetInParagraph : r.offset;
    const sortedResults = [...this.filteredResults].sort((a, b) => resultKey(b) - resultKey(a));
    let successCount = 0;
    this.plugin.restoreScroll(() => {
      for (const result of sortedResults) {
        if (result.suggestions.length === 0)
          continue;
        const replacement = result.suggestions[0];
        const loc = this.plugin.locateResultInEditor(editor, result);
        if (!loc)
          continue;
        try {
          const currentText = editor.getRange(loc.from, loc.to);
          if (currentText === result.original) {
            editor.replaceRange(replacement, loc.from, loc.to);
            successCount++;
          }
        } catch (error) {
          console.error("Apply fix error:", error);
        }
      }
    });
    this.results = [];
    this.filteredResults = [];
    this.activeFilter = "all";
    this.originalText = "";
    if (this.plugin.refreshTimer) {
      clearTimeout(this.plugin.refreshTimer);
      this.plugin.refreshTimer = null;
    }
    this.render();
    new import_obsidian2.Notice(`已修复 ${successCount} 处问题`);
  }
  ignoreAllWords() {
    this.results.forEach((result) => {
      if (!this.plugin.settings.ignoredWords.includes(result.original)) {
        this.plugin.settings.ignoredWords.push(result.original);
      }
    });
    this.plugin.saveSettings();
    this.results = [];
    this.filteredResults = [];
    this.activeFilter = "all";
    this.render();
  }
