function parsePhraseDictionary(builtIns, userLines) {
  const entries = /* @__PURE__ */ new Map();
  const addEntries = (lines) => {
    for (const line of Array.isArray(lines) ? lines : []) {
      if (typeof line !== "string")
        continue;
      const arrowIndex = line.indexOf("=>");
      if (arrowIndex === -1)
        continue;
      const original = line.slice(0, arrowIndex).trim();
      const correct = line.slice(arrowIndex + 2).trim();
      if (!original || !correct || original === correct)
        continue;
      entries.set(original, { original, correct });
    }
  };
  addEntries(builtIns);
  addEntries(userLines);
  return [...entries.values()];
}
function findPhraseMatches(text, entries) {
  if (typeof text !== "string" || !Array.isArray(entries))
    return [];
  const matches = [];
  let start = 0;
  while (start < text.length) {
    let match = null;
    for (const entry of entries) {
      if (!entry || typeof entry.original !== "string" || entry.original.length === 0)
        continue;
      if (text.startsWith(entry.original, start)) {
        match = entry;
        break;
      }
    }
    if (match) {
      const end = start + match.original.length;
      matches.push({ start, end, original: match.original, correct: match.correct });
      start = end;
    } else {
      start++;
    }
  }
  return matches;
}
