var OffsetMapper = class {
  constructor(mappings) {
    this.mappings = mappings;
  }
  cleanOffsetToOriginal(cleanOffset) {
    for (let i = 0; i < this.mappings.length; i++) {
      if (this.mappings[i].cleanOffset === cleanOffset) {
        return this.mappings[i].originalOffset;
      }
    }
    for (let i = this.mappings.length - 1; i >= 0; i--) {
      if (this.mappings[i].cleanOffset !== -1 && this.mappings[i].cleanOffset < cleanOffset) {
        const diff = cleanOffset - this.mappings[i].cleanOffset;
        return this.mappings[i].originalOffset + diff;
      }
    }
    return cleanOffset;
  }
  originalOffsetToClean(originalOffset) {
    for (let i = 0; i < this.mappings.length; i++) {
      if (this.mappings[i].originalOffset === originalOffset) {
        return this.mappings[i].cleanOffset;
      }
    }
    for (let i = this.mappings.length - 1; i >= 0; i--) {
      if (this.mappings[i].originalOffset < originalOffset) {
        const diff = originalOffset - this.mappings[i].originalOffset;
        const targetClean = this.mappings[i].cleanOffset + diff;
        if (targetClean >= 0) {
          return targetClean;
        }
      }
    }
    return originalOffset;
  }
  isValidCleanOffset(offset) {
    return offset >= 0 && offset < this.mappings.length;
  }
  isValidOriginalOffset(offset) {
    var _a;
    return this.mappings.some((m) => m.originalOffset === offset) || offset >= 0 && offset <= ((_a = this.mappings[this.mappings.length - 1]) == null ? void 0 : _a.originalOffset);
  }
};
function splitParagraphs(text) {
  const paragraphs = [];
  const re = /\n\s*\n/g;
  let start = 0;
  let match;
  while ((match = re.exec(text)) !== null) {
    if (match.index > start) {
      paragraphs.push({ start, end: match.index });
    }
    start = re.lastIndex;
  }
  if (start < text.length) {
    paragraphs.push({ start, end: text.length });
  }
  return paragraphs;
}
function locateParagraph(paragraphs, offset) {
  let lo = 0;
  let hi = paragraphs.length - 1;
  while (lo <= hi) {
    const mid = lo + hi >> 1;
    if (offset < paragraphs[mid].start) {
      hi = mid - 1;
    } else if (offset >= paragraphs[mid].end) {
      lo = mid + 1;
    } else {
      return mid;
    }
  }
  return -1;
}
function addParagraphOffsets(results, text) {
  if (!Array.isArray(results) || typeof text !== "string") {
    return results;
  }
  const paragraphs = splitParagraphs(text);
  return results.map((r) => {
    const idx = locateParagraph(paragraphs, r.offset);
    if (idx === -1) {
      return r;
    }
    return { ...r, paragraphIndex: idx, offsetInParagraph: r.offset - paragraphs[idx].start };
  });
}
function applyChangesToOffsets(results, ranges) {
  if (!Array.isArray(results) || !Array.isArray(ranges) || ranges.length === 0) {
    return results;
  }
  const kept = [];
  for (const r of results) {
    const rStart = r.offset;
    const rEnd = r.offset + r.original.length;
    let newOffset = r.offset;
    let invalid = false;
    for (const rg of ranges) {
      if (rEnd <= rg.fromA) {
        break;
      }
      if (rStart >= rg.toA) {
        newOffset += rg.diff;
        continue;
      }
      invalid = true;
      break;
    }
    if (invalid) {
      continue;
    }
    r.offset = newOffset;
    kept.push(r);
  }
  return kept;
}

