var CSCPlugin = class extends import_obsidian5.Plugin {
  constructor() {
    super(...arguments);
    this.view = null;
    this.scheduler = null;
    this.detectionResults = [];
    this.originalText = "";
    this.detectionRequestId = 0;
    this.detectionIncompleteCount = 0;
  }
  async onload() {
    await this.loadSettings();
    await this.syncLicenseStatus();
    this.scheduler = new DetectionScheduler(this.settings, this.app);
    this.lastMarkdownView = this.app.workspace.getActiveViewOfType(import_obsidian5.MarkdownView);
    this.lastMarkdownPath = this.lastMarkdownView?.file?.path;
    this.registerEvent(this.app.workspace.on("active-leaf-change", (leaf) => {
      if (leaf?.view instanceof import_obsidian5.MarkdownView) this.handleMarkdownViewChanged(leaf.view);
    }));
    this.registerEvent(this.app.workspace.on("file-open", () => {
      const view = this.getMarkdownView();
      if (view) this.handleMarkdownViewChanged(view);
    }));
    this.registerEditorExtension([highlightsField, highlightTheme, import_view.EditorView.updateListener.of((update) => {
      if (update.docChanged) {
        this.handleDocChanged(update);
      }
    })]);
    this.registerView(VIEW_TYPE_CSC, (leaf) => {
      this.view = new CSCView(leaf, this);
      return this.view;
    });
    this.addRibbonIcon("spell-check", "中文校对", () => {
      this.activateView();
    });
    this.addCommand({
      id: "check-chinese-typos",
      name: "检测当前文档",
      callback: () => {
        this.startDetection();
      }
    });
    this.addCommand({
      id: "clear-highlights",
      name: "清除编辑器高亮",
      callback: () => {
        this.clearAllHighlights();
      }
    });
    this.addSettingTab(new CSCSettingTab(this.app, this));
  }
  onunload() {
    if (this.view) {
      this.view = null;
    }
    if (this.refreshTimer) {
      clearTimeout(this.refreshTimer);
      this.refreshTimer = null;
    }
    this.scheduler = null;
    this.clearEditorHighlights();
  }
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
    if (this.scheduler) {
      this.scheduler.updateSettings(this.settings);
    }
    this.view?.render?.();
  }
  async setDetectionMode(mode) {
    if (!["quick", "standard", "deep"].includes(mode) || this.detecting || this.modeSaving) return false;
    if (this.settings.detectionMode === mode) return true;
    const previous = this.settings.detectionMode;
    this.modeSaving = true;
    this.settings.detectionMode = mode;
    this.view?.render?.();
    try {
      await this.saveSettings();
      return true;
    } catch (error) {
      this.settings.detectionMode = previous;
      new import_obsidian5.Notice("检测模式保存失败，已恢复原模式");
      console.error("Failed to save detection mode:", error);
      return false;
    } finally {
      this.modeSaving = false;
      this.view?.render?.();
    }
  }
  async syncLicenseStatus() {
    const localLicenseType = activationService.checkLocalLicenseStatus();
    if (localLicenseType !== this.settings.licenseType) {
      this.settings.licenseType = localLicenseType;
      await this.saveSettings();
    }
  }
  isFullVersion() {
    return ActivationService.isFullVersion(this.settings.licenseType);
  }
  canUseMode(mode) {
    return true;
  }
  activateView() {
    var _a;
    const leaf = this.app.workspace.getLeavesOfType(VIEW_TYPE_CSC);
    if (leaf.length > 0) {
      this.app.workspace.revealLeaf(leaf[0]);
      return;
    }
    (_a = this.app.workspace.getRightLeaf(false)) == null ? void 0 : _a.setViewState({
      type: VIEW_TYPE_CSC,
      active: true
    });
  }
  getMarkdownView() {
    const workspace = this.app.workspace;
    const leaves = workspace.getLeavesOfType("markdown");
    const activeFile = workspace.getActiveFile?.();
    const candidates = [workspace.getActiveViewOfType(import_obsidian5.MarkdownView), this.lastMarkdownView, workspace.getMostRecentLeaf?.()?.view];
    const usable = (view) => view instanceof import_obsidian5.MarkdownView && leaves.some((leaf) => leaf.view === view) && (!activeFile || view.file?.path === activeFile.path);
    for (const view of candidates) if (usable(view)) return view;
    if (activeFile) return leaves.map((leaf) => leaf.view).find(usable) || null;
    return null;
  }
  handleMarkdownViewChanged(view) {
    const path = view.file?.path;
    const sameDocument = this.detectionTarget ? this.detectionTarget.view === view && this.detectionTarget.path === path : this.lastMarkdownView === view && this.lastMarkdownPath === path;
    if (!sameDocument) {
      this.clearEditorHighlights();
      this.detectionRequestId = (this.detectionRequestId || 0) + 1;
      this.detecting = false;
      this.detectionResults = [];
      this.detectionTarget = null;
      this.detectionIncompleteCount = 0;
      this.originalText = "";
      if (this.refreshTimer) { clearTimeout(this.refreshTimer); this.refreshTimer = null; }
    }
    this.lastMarkdownView = view;
    this.lastMarkdownPath = path;
    if (!sameDocument && this.view) {
      this.view.activeFilter = "all";
      this.view.setResults([], "");
      this.view.setStatus("idle");
    }
  }
  getEditorView() {
    var _a;
    const mdView = this.detectionTarget ? (this.isDetectionTargetValid() ? this.detectionTarget.view : null) : this.getMarkdownView();
    if (!mdView)
      return null;
    const cm = (_a = mdView.editor) == null ? void 0 : _a.cm;
    return cm || null;
  }
  restoreScroll(fn) {
    const view = this.getEditorView();
    const scrollTop = view ? view.scrollDOM.scrollTop : null;
    fn();
    if (view && scrollTop != null) {
      // 替换触发 CM6 光标可见性滚动，恢复 scrollTop 使视口内容保持原位
      view.scrollDOM.scrollTop = scrollTop;
    }
  }
  async startDetection() {
    if (this.detecting || this.modeSaving) return;
    const activeFile = this.app.workspace.getActiveFile();
    if (!activeFile) {
      new import_obsidian5.Notice("没有打开的文档");
      return;
    }
    const mdView = this.getMarkdownView();
    if (!mdView) {
      new import_obsidian5.Notice("当前视图不是 Markdown 编辑器");
      return;
    }
    const editor = mdView.editor;
    this.handleMarkdownViewChanged(mdView);
    this.clearEditorHighlights();
    if (this.refreshTimer) { clearTimeout(this.refreshTimer); this.refreshTimer = null; }
    const target = { view: mdView, editor, path: mdView.file?.path, mode: this.settings?.detectionMode || "quick" };
    this.detectionTarget = target;
    this.detectionResults = [];
    this.detectionIncompleteCount = 0;
    this.originalText = editor.getValue();
    const selection = editor.getSelection();
    const snapshot = { text: this.originalText, hasSelection: !!selection };
    if (selection) {
      snapshot.selectionRange = { from: editor.posToOffset(editor.getCursor("from")), to: editor.posToOffset(editor.getCursor("to")) };
    }
    this.detecting = true;
    const requestId = this.detectionRequestId = (this.detectionRequestId || 0) + 1;
    this.detectionInvalidated = false;
    this.activateView();
    if (!this.scheduler) {
      this.scheduler = new DetectionScheduler(this.settings, this.app);
    }
    if (this.view) {
      this.view.setStatus("detecting");
    }
    try {
      const results = await this.scheduler.detect(snapshot);
      if (requestId !== this.detectionRequestId) return;
      if (this.app.workspace.getActiveFile()?.path !== target.path) {
        const current = this.getMarkdownView();
        if (current) this.handleMarkdownViewChanged(current);
        return;
      }
      if (!this.isDetectionTargetValid() || this.detectionInvalidated || editor.getValue() !== snapshot.text) {
        throw new Error("检测期间原文或目标标签已变化，请重新检测");
      }
      this.detectionResults = results;
      this.detectionIncompleteCount = results.incompleteCount || 0;
      if (this.view) {
        this.view.setResults(this.detectionResults, this.originalText);
        this.view.setStatus("completed");
      }
      if (this.detectionResults.length > 0) {
        const editorView = this.getEditorView();
        if (editorView) {
          setHighlights(editorView, this.detectionResults);
        }
      }
      if (this.detectionIncompleteCount > 0) {
        new import_obsidian5.Notice(`检测不完整：保留 ${this.detectionResults.length} 条可用建议，部分响应异常或无法定位`);
      } else if (this.detectionResults.length === 0) {
        new import_obsidian5.Notice("太棒了！没有发现问题");
      } else {
        new import_obsidian5.Notice(`发现 ${this.detectionResults.length} 处问题`);
      }
    } catch (error) {
      if (requestId !== this.detectionRequestId) return;
      console.error("Detection error:", error);
      if (this.view) {
        this.view.setStatus("error", error instanceof Error ? error.message : "检测失败");
      }
      new import_obsidian5.Notice("检测失败: " + (error instanceof Error ? error.message : "未知错误"));
    } finally {
      if (requestId === this.detectionRequestId) this.detecting = false;
    }
  }
  locateResultInEditor(editor, result) {
    if (!editor || !result) {
      return null;
    }
    return { from: editor.offsetToPos(result.offset), to: editor.offsetToPos(result.offset + result.original.length) };
  }
  applyFix(result, replacement) {
    const editor = this.getEditor();
    if (!editor) {
      new import_obsidian5.Notice("无法获取编辑器");
      return false;
    }
    try {
      const loc = this.locateResultInEditor(editor, result);
      if (!loc) {
        new import_obsidian5.Notice("文本已被修改或位置偏移，请重新检测");
        return false;
      }
      const currentText = editor.getRange(loc.from, loc.to);
      if (currentText !== result.original) {
        console.log(`文本不匹配: 期望 "${result.original}", 实际 "${currentText}"`);
        new import_obsidian5.Notice("文本已被修改或位置偏移，请重新检测");
        return false;
      }
      // 替换会触发 CM6 updateListener → handleDocChanged 平移后续偏移并移除该项；
      // restoreScroll 抵消替换引起的光标可见性滚动，视口内容保持原位
      this.restoreScroll(() => {
        editor.replaceRange(replacement, loc.from, loc.to);
      });
      return true;
    } catch (error) {
      console.error("Apply fix error:", error);
      new import_obsidian5.Notice("修复失败");
      return false;
    }
  }
  applyAllFixes() {
    const editor = this.getEditor();
    if (!editor) {
      new import_obsidian5.Notice("无法获取编辑器");
      return 0;
    }
    const resultKey = (r) => r.paragraphIndex !== void 0 ? r.paragraphIndex * 1e7 + r.offsetInParagraph : r.offset;
    const sortedResults = [...this.detectionResults].sort((a, b) => resultKey(b) - resultKey(a));
    let successCount = 0;
    this.restoreScroll(() => {
      for (const result of sortedResults) {
        if (result.suggestions.length === 0)
          continue;
        const replacement = result.suggestions[0];
        const loc = this.locateResultInEditor(editor, result);
        if (!loc)
          continue;
        try {
          const currentText = editor.getRange(loc.from, loc.to);
          if (currentText === result.original) {
            editor.replaceRange(replacement, loc.from, loc.to);
            successCount++;
          }
        } catch (error) {
          console.error("Apply fix error:", error);
        }
      }
    });
    this.detectionResults = [];
    this.originalText = "";
    if (this.refreshTimer) {
      clearTimeout(this.refreshTimer);
      this.refreshTimer = null;
    }
    this.clearEditorHighlights();
    if (this.view) {
      this.view.setResults([]);
    }
    new import_obsidian5.Notice(`已修复 ${successCount} 处问题`);
    return successCount;
  }
  renderResults() {
    if (this.detectionResults.length > 0) {
      const editorView = this.getEditorView();
      if (editorView) {
        setHighlights(editorView, this.detectionResults);
      }
    } else {
      this.clearEditorHighlights();
    }
    if (this.view) {
      this.view.setResults(this.detectionResults, this.originalText);
    }
  }
  handleDocChanged(update) {
    if (!this.isDetectionTargetValid() || update.view !== this.detectionTarget.editor.cm) return;
    this.originalText = update.state?.doc?.toString() ?? this.detectionTarget.editor.getValue();
    if (this.detecting) { this.detectionInvalidated = true; return; }
    if (this.detectionResults.length === 0) {
      return;
    }
    const ranges = [];
    update.changes.iterChanges((fromA, toA, fromB, toB, inserted) => {
      ranges.push({ fromA, toA, diff: inserted.length - (toA - fromA) });
    });
    if (ranges.length === 0) {
      return;
    }
    this.detectionResults = applyChangesToOffsets(this.detectionResults, ranges);
    if (this.refreshTimer) {
      clearTimeout(this.refreshTimer);
    }
    this.refreshTimer = setTimeout(() => {
      this.refreshTimer = null;
      this.renderResults();
    }, 150);
  }
  clearEditorHighlights() {
    const editorView = this.getEditorView();
    if (editorView) {
      clearHighlights(editorView);
    }
  }
  clearAllHighlights() {
    this.clearEditorHighlights();
    this.detectionResults = [];
    if (this.view) {
      this.view.setResults([]);
    }
    new import_obsidian5.Notice("已清除编辑器高亮");
  }
  getEditor() {
    return this.isDetectionTargetValid() ? this.detectionTarget.editor : null;
  }
  isDetectionTargetValid() {
    const target = this.detectionTarget;
    if (!target || target.view.editor !== target.editor || target.view.file?.path !== target.path) return false;
    const leaves = this.app?.workspace?.getLeavesOfType?.("markdown");
    return !leaves || leaves.some((leaf) => leaf.view === target.view);
  }
  getResults() {
    return this.detectionResults;
  }
  getOriginalText() {
    return this.originalText;
  }
};
